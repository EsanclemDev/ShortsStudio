import React,{useMemo,useEffect,useState} from 'react';
import {AbsoluteFill,Sequence,useCurrentFrame,useDelayRender} from 'remotion';
import {validateVideo} from './VideoValidator';
import {resolveFrame} from './timeline/TimelineEngine';
import {SceneRenderer} from './renderers/SceneRenderer';
import {AudioEngine} from '../audio/AudioEngine';
import {SubtitleEngine} from '../subtitles/SubtitleEngine';
import {getMouthOpen,type LipSyncData} from '../audio/LipSync';
import type {SubtitleWord} from '../subtitles/SubtitleTypes';
import {loadJson,CaptionsSchema,LipSyncSchema} from './Multimedia';
type Assets={words?:SubtitleWord[];lip?:LipSyncData};
export type VideoRendererProps={video:unknown};
const LoadedVideo:React.FC<{config:ReturnType<typeof validateVideo>}>=({config})=>{
 const frame=useCurrentFrame();
 const {delayRender,continueRender,cancelRender}=useDelayRender();
 const [assets,setAssets]=useState<Assets|null>(null);
 const [handle]=useState(()=>delayRender('Loading director multimedia'));
 useEffect(()=>{let active=true;
 Promise.all([config.subtitles?loadJson(config.subtitles.src,CaptionsSchema):undefined,config.lipsync?loadJson(config.lipsync,LipSyncSchema):undefined]).then(([words,lip])=>{if(active)setAssets({words,lip});}).catch(error=>{if(active)cancelRender(error);});
 return ()=>{active=false;continueRender(handle);};
 },[config,handle,continueRender,cancelRender]);
 useEffect(()=>{if(assets)continueRender(handle);},[assets,handle,continueRender]);
 if(!assets)return null;
 const state=resolveFrame(config,frame);
 const voiceFrame=frame-(config.audio?.voice?.startFrame??0);
 const voiceActive=voiceFrame>=0&&(config.audio?.voice?.durationInFrames===undefined||voiceFrame<config.audio.voice.durationInFrames);
 const mouth=assets.lip&&voiceActive?getMouthOpen(assets.lip,voiceFrame,config.fps):0;
 const resolved={...state,entities:state.entities.map(e=>e.type==='character'&&e.speak?{...e,props:{...e.props,mouthOpen:mouth}}:e)};
 const subtitleWords=assets.words?.map(w=>({...w,startMs:w.startMs+(config.audio?.voice?.startFrame??0)*1000/config.fps,endMs:w.endMs+(config.audio?.voice?.startFrame??0)*1000/config.fps}));
 return <AbsoluteFill style={{background:'#071421'}}><Sequence key={state.scene.id} from={state.startFrame} durationInFrames={state.durationInFrames} layout="none"><SceneRenderer state={resolved}/></Sequence>{config.audio&&<AudioEngine config={config.audio}/>} {config.subtitles&&subtitleWords&&voiceActive&&<SubtitleEngine config={{...config.subtitles,words:subtitleWords}}/>}</AbsoluteFill>;
};
export const VideoRenderer:React.FC<VideoRendererProps>=({video})=>{const config=useMemo(()=>validateVideo(video),[video]);return <LoadedVideo key={JSON.stringify(config)} config={config}/>;};
